#include <stdio.h>

int main() {
    // == igualdade
    // != deference
    // < menor
    // <= menor ou igual
    // > maior
    // >= maior ou igual

    // 0 significa falso
    // 1 significa verdadeiro

    
    printf("2 == 5? %i\n", 2 == 5);
    printf("2 != 5? %i\n", 2 != 5);
    printf("2 < 5? %i\n", 2 < 5);
    printf("2 <= 5? %i\n", 2 <= 5);
    printf("2 > 5? %i\n", 2 > 5);
    printf("2 >= 5? %i\n", 2 >= 5);


    return 0;
}